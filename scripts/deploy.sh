verify_container_health() {
    local cid health status timeout="$1" waited=0
    cid=$(docker compose ps -q backend 2>/dev/null || true)
    [ -n "$cid" ] || { vfail "backend has no container"; return 0; }

    while :; do
        health=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$cid")
        status=$(docker inspect -f '{{.State.Status}}' "$cid")
        [ "$status" = "running" ] || { vfail "backend container is '$status'"; return 0; }
        case "$health" in
            healthy) ok "backend is healthy (${waited}s)"; break ;;
            none)    warn "backend has no healthcheck; accepting 'running'"; break ;;
            unhealthy)
                vfail "backend healthcheck reports unhealthy"
                docker inspect -f '{{range .State.Health.Log}}{{.Output}}{{end}}' "$cid" | tail -5 | sed 's/^/        /'
                return 0 ;;
        esac
        [ "$waited" -ge "$timeout" ] && { vfail "backend still '$health' after ${timeout}s"; return 0; }
        sleep 5; waited=$((waited + 5))
    done

    # docker-compose.yml defines no healthcheck for `sync`, so "healthy" is not
    # available. Watch for a crash loop instead: a container that keeps dying is
    # restarted by `restart: unless-stopped` and looks "running" between deaths.
    cid=$(docker compose ps -q sync 2>/dev/null || true)
    [ -n "$cid" ] || { vfail "sync has no container"; return 0; }
    local r0 r1
    r0=$(docker inspect -f '{{.RestartCount}}' "$cid")
    info "watching sync for ${SYNC_SETTLE}s (no healthcheck defined for it)"
    sleep "$SYNC_SETTLE"
    status=$(docker inspect -f '{{.State.Status}}' "$cid")
    r1=$(docker inspect -f '{{.RestartCount}}' "$cid")
    if [ "$status" != "running" ]; then
        vfail "sync container is '$status' after ${SYNC_SETTLE}s"
        docker compose logs --tail=30 sync | sed 's/^/        /' || true
    elif [ "$r1" != "$r0" ]; then
        vfail "sync restarted $((r1 - r0)) time(s) in ${SYNC_SETTLE}s -- it is crash-looping"
        docker compose logs --tail=30 sync | sed 's/^/        /' || true
    else
        ok "sync is running and has not restarted (RestartCount $r1)"
    fi
}

verify_api_health() {
    local waited=0 code body opts
    opts=$(curl_base)
    while :; do
        set +e
        # shellcheck disable=SC2086
        code=$(curl $opts -o /dev/null -w '%{http_code}' "$BASE_URL/api/health" 2>/dev/null)
        set -e
        [ "$code" = "200" ] && break
        if [ "$waited" -ge "$API_TIMEOUT" ]; then
            vfail "GET $BASE_URL/api/health returned $code after ${API_TIMEOUT}s (want 200)"
            return 0
        fi
        sleep 5; waited=$((waited + 5))
    done
    # shellcheck disable=SC2086
    body=$(curl $opts "$BASE_URL/api/health" 2>/dev/null)
    case "$body" in
        *'"status"'*'"healthy"'*) ok "GET /api/health -> 200 healthy (${waited}s)" ;;
        *) vfail "GET /api/health -> 200 but body is not healthy: $body" ;;
    esac
}

# ---------------------------------------------------------------------------
# The nginx /health endpoint, read as BYTES
# ---------------------------------------------------------------------------
#
# THE SECOND CHECK THAT WAS MISSING, and the reason this one reads a body.
#
# `location = /health` lived in the :80 server of
# nginx/sites/production/production.conf and in no other server block. A
# location is matched only inside the server that handled the request, so over
# TLS -- which is every real request, and every external monitor -- /health fell
# through to `location /`, matched `try_files $uri $uri/ /index.html` and
# returned:
#
#     200 OK   content-type: text/html   <!DOCTYPE html>...
#
# verify_security_headers() below probed that exact URL and reported "200, 5/5
# headers", because it reads the status line and the headers and never the body.
# So did the CI header job. Both were right about what they measured and both
# were reporting on a health endpoint that had been answering with the homepage
# for as long as the 443 server had existed.
#
# A status-code check cannot see this class of failure. Assert the bytes.
#
# Also probed over plain HTTP on the same host: :80 is where the container
# healthcheck (`curl -f http://localhost/health`) and certbot's HTTP-01 renewal
# live, and the two schemes must agree. If they ever differ again, this says so
# during the deploy rather than leaving it to a monitor that cannot tell.
verify_health_endpoint() {
    local opts body code ctype url http_url fails=0
    opts=$(curl_base)
    url="$BASE_URL/health"

    probe_health() {
        local target="$1" label="$2"
        set +e
        # shellcheck disable=SC2086
        code=$(curl $opts -o /dev/null -w '%{http_code}' "$target" 2>/dev/null)
        # Header names are lowercased on HTTP/2 and mixed-case on HTTP/1.1; the
        # 443 server sets `http2 on`, so fold before matching.
        # shellcheck disable=SC2086
        ctype=$(curl $opts -o /dev/null -D - "$target" 2>/dev/null \
                | tr -d '\r' | tr '[:upper:]' '[:lower:]' \
                | awk '/^content-type:/{print $2}' | head -1)
        # shellcheck disable=SC2086
        body=$(curl $opts "$target" 2>/dev/null)
        set -e

        local problems=""
        [ "$code" = "200" ] || problems="$problems status=$code(want 200);"
        case "$ctype" in
            text/plain*) ;;
            *) problems="$problems content-type=${ctype:-none}(want text/plain);" ;;
        esac
        # $(...) strips the trailing newline, so this compares against "OK".
        [ "$body" = "OK" ] || problems="$problems body is not OK;"

        if [ -n "$problems" ]; then
            printf '  %-34s %-5s %s%s%s\n' "$label" "$code" "$C_RED" "$problems" "$C_OFF"
            printf '      body was: %s\n' "$(printf '%s' "$body" | head -c 120 | tr '\n' ' ')"
            fails=$((fails + 1))
        else
            printf '  %-34s %-5s %stext/plain "OK"%s\n' "$label" "$code" "$C_GRN" "$C_OFF"
        fi
    }

    probe_health "$url" "$url"

    # Same endpoint over plaintext on the same host, so a divergence between the
    # schemes is caught during the deploy rather than by a monitor that cannot
    # see it. Skipped in two cases:
    #   BASE_URL is already http://  -- that is the same probe twice
    #   BASE_URL carries an explicit port -- :443 does not imply :80 on the same
    #     number, and rewriting the scheme while keeping the port would probe
    #     TLS with plaintext and fail a good deploy. A false red here costs more
    #     than the coverage it buys.
    local hostport
    case "$BASE_URL" in
        https://*)
            hostport="${BASE_URL#https://}"
            hostport="${hostport%%/*}"
            case "$hostport" in
                *:*) info "skipping the plaintext /health probe: BASE_URL names an explicit port ($hostport)" ;;
                *)   http_url="http://${BASE_URL#https://}/health"
                     probe_health "$http_url" "$http_url" ;;
            esac
            ;;
    esac

    if [ "$fails" -ne 0 ]; then
        vfail "$fails /health probe(s) did not return exactly 'OK' as text/plain"
        bad "a 200 is not enough here: the failure mode is a 200 carrying the"
        bad "homepage, which every external monitor reads as healthy. Check that"
        bad "every server block includes snippets/health.conf --"
        bad "  python3 scripts/ci-nginx-health.py"
        return 0
    fi
    ok "/health returns text/plain \"OK\" on every scheme"
}

verify_login_roundtrip() {
    # This is the check that would have caught a broken bcrypt bump.
    #
    # It must use a username that EXISTS. backend/app/api/auth.py:167 reads
    #     if user is None or not verify_password(...)
    # and `or` short-circuits, so a login for a nonexistent user returns 401
    # without ever calling bcrypt.checkpw. A 401 for "nosuchuser" therefore
    # proves nothing at all about bcrypt. With a real username and a wrong
    # password the comparison actually runs: 401 means checkpw executed and
    # returned False; 500 means it raised.
    #
    # Side effect, by design: each run appends one `login_failed` row to
    # audit_logs (auth.py:169-176), attributed to the admin username. There is
    # no lockout logic, so repeated runs are safe.
    local user pass code body opts
    user=$(env_get ADMIN_USERNAME admin)
    if command -v openssl >/dev/null 2>&1; then
        pass="deploy-verify-$(openssl rand -hex 16)"
    else
        pass="deploy-verify-$$-$(date +%s)-${RANDOM}${RANDOM}"
    fi
    opts=$(curl_base)

    local attempt=1
    while :; do
        set +e
        # shellcheck disable=SC2086
        body=$(curl $opts -o /dev/null -w '%{http_code}' \
            -X POST \
            --data-urlencode "username=$user" \
            --data-urlencode "password=$pass" \
            "$BASE_URL/api/auth/token" 2>/dev/null)
        set -e
        code="$body"
        # nginx applies `limit_req zone=auth_limit ... rate=3r/s` to this exact
        # location (nginx/sites/default.conf:65). Back off rather than reporting
        # a rate limit as an auth failure.
        if [ "$code" = "429" ] || [ "$code" = "503" ]; then
            [ "$attempt" -ge 4 ] && { vfail "POST /api/auth/token kept returning $code (nginx rate limit)"; return 0; }
            warn "POST /api/auth/token -> $code (rate limited), retrying in 5s"
            sleep 5; attempt=$((attempt + 1)); continue
        fi
        break
    done

    case "$code" in
        401) ok "POST /api/auth/token (user '$user', wrong password) -> 401; the bcrypt verify path ran" ;;
        200) vfail "POST /api/auth/token -> 200 for a random password. Authentication is BROKEN OPEN." ;;
        500|502|504)
            vfail "POST /api/auth/token -> $code. verify_password raised instead of returning False."
            vfail "That is the signature of an incompatible bcrypt; check the pin in backend/requirements.txt."
            docker compose logs --tail=40 backend | sed 's/^/        /' || true ;;
        *)  vfail "POST /api/auth/token -> $code (want 401)" ;;
    esac
}

# ---------------------------------------------------------------------------
# The encode/decode round trip verify_login_roundtrip() cannot reach
# ---------------------------------------------------------------------------
#
# See "What 8da2367 exposed" in the header. verify_login_roundtrip() above
# proves bcrypt ran, by design, and just as by design it never mints a token:
# auth.py's `if user is None or not verify_password(...)` returns 401 before
# create_access_token() is called. python-jose went 3.3.0 -> 3.5.0 in exactly
# that unreached path on the 8da2367 deploy.
#
# This calls the app's own create_access_token()/decode_access_token()
# (backend/app/core/security.py) inside the running container -- the same
# functions a real login uses -- with synthetic claims that touch no database
# row and no admin credential, and asserts the decoded payload is exactly what
# was encoded. It is independent of verify_login_roundtrip(): that one proves
# a bad password is rejected, this one proves a minted token round-trips.
# Neither can stand in for the other, so both run.
verify_jwt_roundtrip() {
    local cid out rc
    cid=$(docker compose ps -q backend 2>/dev/null || true)
    if [ -z "$cid" ]; then
        vfail "backend has no container; cannot verify the JWT encode/decode round trip"
        return 0
    fi

    set +e
    out=$(docker compose exec -T backend python3 - <<'PY'
import sys
from datetime import timedelta

from app.core.security import create_access_token, decode_access_token

claims = {"sub": "__deploy_verify__", "user_id": -1, "role": "deploy-verify"}
token = create_access_token(dict(claims), expires_delta=timedelta(minutes=5))
decoded = decode_access_token(token)

if decoded is None:
    print("decode_access_token returned None for a token this process just minted")
    sys.exit(1)

problems = []
if decoded.username != claims["sub"]:
    problems.append("username: got %r want %r" % (decoded.username, claims["sub"]))
if decoded.user_id != claims["user_id"]:
    problems.append("user_id: got %r want %r" % (decoded.user_id, claims["user_id"]))
if decoded.role != claims["role"]:
    problems.append("role: got %r want %r" % (decoded.role, claims["role"]))
if not decoded.jti:
    problems.append("jti: empty")

if problems:
    print("; ".join(problems))
    sys.exit(1)

print("sub=%s user_id=%s role=%s jti=%s" % (decoded.username, decoded.user_id, decoded.role, decoded.jti))
PY
)
    rc=$?
    set -e

    if [ "$rc" -eq 0 ]; then
        ok "create_access_token -> decode_access_token round-trip matches ($out)"
    else
        vfail "JWT encode/decode round trip failed inside the backend container (exit $rc): $out"
        bad "this is the python-jose path bumped 3.3.0 -> 3.5.0 in the 8da2367 deploy;"
        bad "verify_login_roundtrip()'s 401 short-circuits before ever reaching it"
        docker compose logs --tail=20 backend | sed 's/^/        /' || true
    fi
}

verify_bcrypt_pin() {
    # Closes the loop on the reason this script exists: prove the container is
    # running the version requirements.txt asks for, not whatever the last
    # unpinned resolve happened to fetch.
    local pinned running
    pinned=$(grep -m1 -E '^bcrypt==' backend/requirements.txt 2>/dev/null | cut -d= -f3 || true)
    if [ -z "$pinned" ]; then
        warn "backend/requirements.txt has no exact 'bcrypt==' pin at this SHA; skipping the version check"
        return 0
    fi
    set +e
    running=$(docker compose exec -T backend python -c \
        'import importlib.metadata as m; print(m.version("bcrypt"))' 2>/dev/null | tr -d ' \r\n')
    set -e
    if [ -z "$running" ]; then
        warn "could not read the bcrypt version from the backend container; skipping"
        return 0
    fi
    if [ "$running" = "$pinned" ]; then
        ok "bcrypt $running in the container matches the pin in requirements.txt"
    else
        vfail "bcrypt mismatch: container has $running, requirements.txt pins $pinned"
        vfail "the image was not rebuilt from this checkout"
    fi
}

# ---------------------------------------------------------------------------
# frontend/public/, proved on the live site
# ---------------------------------------------------------------------------
#
# See "What 8da2367 exposed" in the header. Nothing above this line reads a
# single byte of what nginx actually serves from root /var/www/public --
# verify_api_health()/verify_login_roundtrip() talk to the backend, and
# verify_health_endpoint()/verify_security_headers() read status lines and
# headers, never bodies. admin.js and admin.css could ship broken, or not ship
# at all, and every check so far would still say green.
#
# Fetched over HTTP through nginx, not `docker compose exec cat`: exec would
# only prove the bytes exist somewhere in the container's filesystem, not that
# a location block, an alias, or a cached response actually serves them to a
# client. Same reasoning as scripts/nginx-apply.sh check(), aimed at
# frontend/public/ instead of nginx/.
verify_frontend_assets() {
    if [ "$FRONTEND_TOUCHED" -ne 1 ]; then
        ok "no frontend/public/ changes in this deploy; nothing to prove"
        return 0
    fi

    step "Proving nginx is serving this checkout's frontend/public/"
    local opts rel url want got code fails=0 checked=0
    opts=$(curl_base)

    while IFS= read -r rel; do
        [ -n "$rel" ] || continue
        url="$BASE_URL/${rel#frontend/public/}"
        checked=$((checked + 1))

        if [ ! -f "$rel" ]; then
            # Deleted by this deploy. NOT checked as "must not be 200": every
            # location here inherits `try_files $uri $uri/ /index.html` (or
            # .../admin/index.html under the alias), confirmed against a live
            # container, so nginx answers a deleted path with 200 and the SPA
            # shell by design. That is not a stale mount; it is try_files
            # working as configured, and asserting non-200 here would fail
            # every legitimate deletion.
            #
            # The actual failure this must catch is narrower: something still
            # serving the FILE'S OWN pre-deletion bytes -- a stale mount, a
            # cached layer, or a dangling alias that never noticed the delete.
            # So compare live bytes to the pre-deletion content instead of
            # reasoning about status codes at all.
            local old
            old=$(git show "$PREV_SHA:$rel" 2>/dev/null | sha256sum | cut -d' ' -f1) || old=""
            set +e
            # shellcheck disable=SC2086
            got=$(curl $opts "$url" 2>/dev/null | sha256sum | cut -d' ' -f1)
            # shellcheck disable=SC2086
            code=$(curl $opts -o /dev/null -w '%{http_code}' "$url" 2>/dev/null)
            set -e
            if [ -n "$old" ] && [ "$got" = "$old" ]; then
                bad "$url -- deleted in $TARGET_SHA but still serving its old bytes (HTTP $code)"
                fails=$((fails + 1))
            else
                ok "$url -- deleted, no longer serving the old bytes (HTTP $code)"
            fi
            continue
        fi

        want=$(sha256sum "$rel" | cut -d' ' -f1)
        set +e
        # shellcheck disable=SC2086
        got=$(curl $opts "$url" 2>/dev/null | sha256sum | cut -d' ' -f1)
        # shellcheck disable=SC2086
        code=$(curl $opts -o /dev/null -w '%{http_code}' "$url" 2>/dev/null)
        set -e

        if [ "$code" != "200" ]; then
            bad "$url -- HTTP $code fetching a file that exists in the checkout"
            fails=$((fails + 1))
        elif [ "$got" != "$want" ]; then
            bad "$url -- SERVING STALE CONTENT"
            bad "    checkout  $rel  ${want:0:12}"
            bad "    live      $url  ${got:0:12}"
            fails=$((fails + 1))
        else
            ok "$url  ${want:0:12}"
        fi
    done <<EOF
$FRONTEND_CHANGED_FILES
EOF

    if [ "$fails" -ne 0 ]; then
        vfail "$fails of $checked changed frontend/public/ file(s) do not match this checkout"
        bad "backend and sync may be on the new code; nginx's view of frontend/public/ is not."
        bad "docker-compose.yml uses a directory mount, so this should be impossible -- if it"
        bad "just happened anyway, recreate nginx so docker re-resolves it:"
        bad "  cd $DEPLOY_DIR && docker compose up -d --force-recreate nginx"
        return 0
    fi
    ok "all $checked changed frontend/public/ file(s) match the checkout byte-for-byte"
}

# ---------------------------------------------------------------------------
# Security headers, probed on the live site
# ---------------------------------------------------------------------------
#
# THE CHECK THAT WAS MISSING. /api/health and the login round-trip both passed
# on 2026-08-31 while every security header on the site was six months old --
# they cannot distinguish a working deploy from one that did nothing, because
# neither of them reads anything nginx produces.
#
# Probed per PATH, not once, because add_header does not inherit: the whole
# class of bug here is one location silently dropping the set that its parent
# defines. A single probe of `/` would have passed with /admin still bare.
#
# Paths chosen to cover every block in sites/production/production.conf that
# defines an add_header of its own, plus one that defines none:
#   /                    server-level set, static location, no add_header
#   /admin/              adds X-Robots-Tag  -> must not lose the other five
#   /css/style.css       adds Cache-Control -> nested location, same trap
#   /img/favicon.svg     same location, and the one where CSP actually matters
#   /api/health          proxied to backend, no add_header at that level
#   /health              nginx's own endpoint, an `include`d location in both
#                        the :80 and :443 servers. Headers only here; the bytes
#                        are asserted by verify_health_endpoint() above, which
#                        exists because this function reported "200, 5/5" on a
#                        /health that was serving the homepage.
#   /404.html            error page: proves `always` is doing its job on 4xx
#   /nope-404            a real 404 through try_files, same reason
#   /FreeBSD/            autoindex, the highest-traffic path on the site
verify_security_headers() {
    local opts scheme
    opts=$(curl_base)
    case "$BASE_URL" in https://*) scheme=https ;; *) scheme=http ;; esac

    # HSTS is set only in the 443 server, and deliberately absent from dev.conf
    # and bootstrap.conf: it is meaningless over plaintext (RFC 6797 sec. 7.2)
    # and pinning it from a dev box would poison localhost for every other
    # project on that machine.
    local -a want=(x-frame-options x-content-type-options referrer-policy content-security-policy)
    [ "$scheme" = "https" ] && want+=(strict-transport-security)

    local -a paths=(/ /admin/ /css/style.css /img/favicon.svg /api/health /health /404.html /nope-deploy-probe-404 /FreeBSD/)
    local path hdrs missing h code fails=0

    printf '  %-28s %-5s %s\n' "PATH" "CODE" "HEADERS"
    for path in "${paths[@]}"; do
        set +e
        # shellcheck disable=SC2086
        hdrs=$(curl $opts -o /dev/null -D - "$BASE_URL$path" 2>/dev/null | tr -d '\r' | tr '[:upper:]' '[:lower:]')
        set -e
        code=$(printf '%s\n' "$hdrs" | awk '/^http\//{c=$2} END{print c}')
        if [ -z "$code" ]; then
            bad "$path -- no response from $BASE_URL"
            fails=$((fails + 1))
            continue
        fi
        missing=""
        for h in "${want[@]}"; do
            printf '%s\n' "$hdrs" | grep -q "^$h:" || missing="$missing $h"
        done
        if [ -n "$missing" ]; then
            printf '  %-28s %-5s %sMISSING:%s%s\n' "$path" "$code" "$C_RED" "$C_OFF" "$missing"
            fails=$((fails + 1))
        else
            printf '  %-28s %-5s %s%d/%d ok%s\n' "$path" "$code" "$C_GRN" "${#want[@]}" "${#want[@]}" "$C_OFF"
        fi
    done

    if [ "$fails" -ne 0 ]; then
        # One vfail, then plain bad() for the advice. vfail increments
        # VERIFY_FAILURES, and three calls for one problem would report
        # "3 checks failed" for a single cause.
        vfail "$fails of ${#paths[@]} probed paths are missing security headers"
        bad "if this deploy changed nginx/, the change did not take effect --"
        bad "run 'scripts/nginx-apply.sh check' before believing anything else"
        return 0
    fi
    ok "all ${#paths[@]} probed paths carry the full ${#want[@]}-header set"

    # The CSP is defined once, by the map in nginx/nginx.conf. Four blocks emit
    # it. If two of them disagree, one of them is stale.
    local policies
    policies=$(for path in "${paths[@]}"; do
        # shellcheck disable=SC2086
        curl $opts -o /dev/null -D - "$BASE_URL$path" 2>/dev/null \
            | tr -d '\r' | grep -i '^content-security-policy:' | cut -d' ' -f2-
    done | sort -u | wc -l | tr -d ' ')
    if [ "$policies" = "1" ]; then
        ok "one Content-Security-Policy value across all probed paths"
    else
        vfail "$policies different Content-Security-Policy values are being served"
        bad "the map in nginx/nginx.conf is the single source; a block is stale"
    fi
}

# The check that would have caught the whole class of problem this change
# exists for: after the deploy, does the schema the containers are running
# against actually match the models in the image that is serving?
#
# `migrate.sh check` runs `alembic check` inside the freshly built backend
# image, so it compares THIS commit's shared/models/ against the live database.
# A missing migration, a --skip-migrations that should not have been used, or a
# migration that did not cover every model change all surface here rather than
# as a 500 on the first request that touches the new column.
verify_schema_at_head() {
    if [ ! -x scripts/migrate.sh ]; then
        vfail "scripts/migrate.sh missing; cannot verify the schema"
        return 0
    fi
    local rc=0
    scripts/migrate.sh check >/dev/null 2>&1 || rc=$?
    case "$rc" in
        0) ok "schema matches shared/models/ (alembic check clean)" ;;
        4) vfail "the live schema does NOT match shared/models/ -- run: scripts/migrate.sh check" ;;
        *) vfail "scripts/migrate.sh check exited $rc" ;;
    esac
}

verify_all() {
    PHASE="verifying"
    step "Verifying"
    verify_container_health "$HEALTH_TIMEOUT"
    verify_schema_at_head
    verify_api_health
    verify_health_endpoint
    verify_login_roundtrip
    verify_jwt_roundtrip
    verify_bcrypt_pin
    verify_frontend_assets
    step "Verifying security headers on the live site"
    verify_security_headers

    if [ "$VERIFY_FAILURES" -ne 0 ]; then
        banner "$C_RED" "DEPLOY COMPLETED BUT VERIFICATION FAILED ($VERIFY_FAILURES check(s))" \
            "The new code from $TARGET_SHA IS SERVING LIVE TRAFFIC." \
            "This is not a safe state to walk away from." \
            "" \
            "Roll back:" \
            "  cd $DEPLOY_DIR && scripts/deploy.sh --rollback $PREV_SHA" \
            "" \
            "Or investigate:" \
            "  docker compose ps" \
            "  docker compose logs --tail=200 backend sync"
        PHASE="done"
        exit 4
    fi
    ok "all post-deploy checks passed"
}

# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
main() {
    preflight_common

    if [ "$MODE" = "ci-check-only" ]; then
        # Deliberately does not require docker or the deploy directory, so the
        # gate can be exercised anywhere -- including from a laptop, and from a
        # test that proves the red / green / no-run branches really differ.
        if [ -d "$DEPLOY_DIR/.git" ]; then cd "$DEPLOY_DIR"; fi
        derive_repo_slug
        local sha
        if printf '%s' "$TARGET_REF" | grep -qiE '^[0-9a-f]{40}$'; then
            sha="$TARGET_REF"
        else
            git rev-parse --git-dir >/dev/null 2>&1 \
                || die "--ci-check-only with a non-SHA ref needs a git checkout; pass a full 40-char SHA or --dir"
            git fetch --prune origin >/dev/null 2>&1 || warn "git fetch failed; resolving '$TARGET_REF' from local refs"
            sha=$(git rev-parse --verify --quiet "refs/remotes/origin/$TARGET_REF^{commit}" \
                  || git rev-parse --verify "${TARGET_REF}^{commit}") \
                  || die "cannot resolve '$TARGET_REF'"
        fi
        step "CI gate check only: $REPO_SLUG @ $sha"
        evaluate_ci "$sha"
        PHASE="done"
        [ "$CI_STATE" = "GREEN" ] && exit 0
        exit 2
    fi

    preflight_deploy
    derive_repo_slug

    PREV_SHA=$(git rev-parse HEAD)
    local prev_desc
    prev_desc=$(git --no-pager log -1 --format='%s' "$PREV_SHA")

    banner "$C_BLU" "bsdmirror deploy" \
        "directory       $DEPLOY_DIR" \
        "repo            $REPO_SLUG" \
        "services        $SERVICES  (nginx / postgres / redis untouched)" \
        "mode            $MODE$([ "$DRY_RUN" -eq 1 ] && printf ' (--dry-run)')" \
        "" \
        "CURRENT SHA     $PREV_SHA" \
        "                $prev_desc" \
        "" \
        "Roll back to the current state at any time with:" \
        "  scripts/deploy.sh --rollback $PREV_SHA"

    resolve_target

    if [ "$TARGET_SHA" = "$PREV_SHA" ] && [ "$MODE" != "rollback" ]; then
        info "already at $TARGET_SHA"
        confirm "Rebuild and recreate anyway?" || { info "nothing to do"; PHASE="done"; exit 0; }
    fi

    require_ci_green "$TARGET_SHA"
    require_clean_tree

    if [ "$DRY_RUN" -eq 0 ]; then
        step "Validating compose before touching anything"
        docker compose config -q || die_gate "docker compose config failed; refusing to deploy a stack that does not parse"
        ok "docker compose config -q clean"
        step "Dependencies"
        dependencies_must_be_up
        require_no_sync_in_progress
    else
        warn "--dry-run: skipping compose validation, dependency and sync-activity gates"
    fi

    # Verification targets the public URL because backend publishes no ports --
    # it is only reachable through nginx (docker-compose.yml has no `ports` for
    # it and the `backend` network is internal: true).
    if [ -z "$BASE_URL" ]; then
        local domain; domain=$(env_get DOMAIN "")
        if [ -n "$domain" ] && [ "$domain" != "localhost" ]; then
            BASE_URL="https://$domain"
        else
            BASE_URL="http://localhost"
        fi
    fi
    info "verification base URL: $BASE_URL"

    detect_nginx_change
    detect_migration_change
    detect_frontend_change

    if [ "$DRY_RUN" -eq 0 ]; then
        confirm "Deploy $TARGET_SHA to $DEPLOY_DIR?" || die_gate "aborted by operator; nothing was done"
    fi

    move_checkout
    build_images
    deploy_migrations
    recreate_services
    deploy_nginx

    if [ "$DRY_RUN" -eq 1 ]; then
        PHASE="done"
        banner "$C_BLU" "--dry-run finished" \
            "Every gate ran. No git, build or container command was executed."
        exit 0
    fi

    verify_all

    PHASE="done"
    local nginx_note="nginx  not changed by this deploy, left running"
    [ "$NGINX_TOUCHED" -eq 1 ] && nginx_note="nginx  config applied and gracefully reloaded"
    [ "$NGINX_TOUCHED" -eq 1 ] && [ "$SKIP_NGINX" -eq 1 ] && nginx_note="nginx  CHANGED BUT SKIPPED (--skip-nginx)"

    local db_note="db     no migration in this deploy; schema verified at head"
    [ "$MIGRATIONS_TOUCHED" -eq 1 ] && db_note="db     migration applied; schema verified at head"
    [ "$SKIP_MIGRATIONS" -eq 1 ] && db_note="db     MIGRATIONS SKIPPED (--skip-migrations)"

    banner "$C_GRN" "DEPLOYED AND VERIFIED" \
        "$PREV_SHA" \
        "  -> $TARGET_SHA" \
        "" \
        "$nginx_note" \
        "$db_note" \
        "" \
        "Roll back with:" \
        "  cd $DEPLOY_DIR && scripts/deploy.sh --rollback $PREV_SHA"

    if [ "$CHECKOUT_STYLE" = "detached" ]; then
        warn "HEAD is detached at $TARGET_SHA."
        warn "The next 'git pull' here will do nothing useful. Return to the branch with:"
        warn "  cd $DEPLOY_DIR && scripts/deploy.sh main"
    fi
}

# Executing this file deploys. Sourcing it defines the gates without running
# anything, so require_clean_tree / evaluate_ci / require_no_sync_in_progress
# can be exercised on their own -- which is the only way to test a gate whose
# whole job is to refuse.
if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    main "$@"
fi
