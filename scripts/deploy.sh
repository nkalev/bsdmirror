#!/usr/bin/env bash
#
# bsdmirror - gated deploy
#
# Why this exists
# ---------------
# This repo's first 36 commits contain 30 post-deploy "Fix ..." commits. The
# loop that produces them is: push, pull on the server, find out. On
# 2026-08-30 a push to main was pulled to production within minutes, before CI
# had finished its first run on that SHA; the same rebuild also moved bcrypt
# from 4.x to 5.0.0 in the login path unreviewed. Both were fine. Neither was
# checked.
#
# This script makes that specific sequence hard. It refuses to deploy a SHA
# whose CI is not green, refuses to deploy on top of uncommitted work, refuses
# to interrupt a running rsync, and verifies afterwards -- including a login
# round-trip, which is the check that would have caught a broken bcrypt bump.
#
# It builds and recreates only `backend` and `sync`. postgres and redis are never
# touched. nginx is never RECREATED -- but as of 2026-08-31 it is reloaded, and
# that gap is why this paragraph used to end here.
#
# What happened on 2026-08-31
# ---------------------------
# A security-header change was deployed. This script printed DEPLOYED AND
# VERIFIED. Not one header changed. Three independent causes:
#
#   1. This script recreated backend and sync with --no-deps and never looked at
#      nginx/. Correct for Python changes, silently wrong for anything else.
#   2. docker-compose.yml bind-mounted two INDIVIDUAL FILES into nginx. A
#      single-file bind mount pins an inode, and `git checkout` renames a new
#      file over the old name rather than editing in place. The container had
#      been reading a 2026-02-12 inode ever since. `nginx -t` and `nginx -s
#      reload` would both have succeeded against that stale file.
#   3. The config that served production, nginx/sites/production.conf, was
#      generated by ssl-setup.sh and untracked, so git could not update it at
#      all. It had drifted to 5 add_header directives against 21.
#
# (2) and (3) are fixed in docker-compose.yml and scripts/ssl-setup.sh. (1) is
# fixed here: deploy_nginx() below detects a deploy that moves anything under
# nginx/, re-renders the one remaining generated file, PROVES the container is
# reading this checkout by comparing digests, validates, and reloads gracefully
# rather than restarting. verify_security_headers() then probes the live site,
# because /api/health and a login round-trip cannot tell a working deploy from
# one that did nothing.
#
# On "gracefully": a SIGHUP reload leaves in-flight HTTP/1.1 mirror downloads
# intact (measured, 12/12), which a restart would not. It can still truncate a
# long HTTP/2 transfer while the old worker shuts down (measured, 3 of 4). See
# the note in scripts/nginx-apply.sh graceful_reload().
#
# What 8da2367 exposed
# --------------------
# 8da2367 was fine, same as 2026-08-30 was fine -- and this script's own
# verification could not have told the difference, for two reasons unrelated
# to nginx:
#
#   1. docker-compose.yml also bind-mounts frontend/public/ straight into
#      nginx (`./frontend/public:/var/www/public:ro`), read-only, with no
#      build step in between. This script builds and recreates backend and
#      sync; nothing here has ever built, gated or verified frontend/public/.
#      8da2367 shipped admin.js (-48/+48) and admin.css (+65) that way.
#
#      There is no point in the sequence where this CAN be gated: the mount is
#      live, so move_checkout() below is the instant the change takes effect,
#      whether or not the operator would have said yes. So this script does
#      the two things that are actually possible instead of pretending
#      otherwise: detect_frontend_change() lists what changed under
#      frontend/public/ before the confirmation prompt, so a "no" still means
#      something, and verify_frontend_assets() -- reusing deploy_nginx()'s own
#      logic of proving rather than assuming -- fetches every changed file
#      over HTTP from the live site afterward and compares it to this checkout
#      on disk, which is exactly what would catch a stale mount, a cached
#      layer, or a path that never reached nginx.
#
#   2. verify_login_roundtrip() posts a real username with a random wrong
#      password and asserts 401. That is deliberately as far as it goes -- it
#      must never touch the real admin password -- but auth.py returns that
#      401 on an `or` short-circuit BEFORE create_access_token() is ever
#      called. 8da2367's headline change was python-jose 3.3.0 -> 3.5.0 in
#      exactly the path that 401 never reaches, so nothing in this script
#      could have distinguished a working encode/decode from a broken one.
#      verify_jwt_roundtrip() closes that: it calls the app's own
#      create_access_token() / decode_access_token()
#      (backend/app/core/security.py) inside the running container with
#      synthetic claims, and asserts the decoded payload is exactly what was
#      encoded. It runs alongside verify_login_roundtrip(), not instead of
#      it -- the two prove different things.
#
# Usage
# -----
#   scripts/deploy.sh [REF]                 deploy a ref (default: main)
#   scripts/deploy.sh --rollback <SHA>      redeploy a previous SHA
#   scripts/deploy.sh --ci-check-only <REF> evaluate the CI gate and exit
#   scripts/deploy.sh --help
#
# Database migrations
# -------------------
# As of the Alembic adoption, the schema is no longer created by the backend at
# startup -- `Base.metadata.create_all` is gone, and create_all only ever
# created missing TABLES anyway, silently ignoring every column, type and
# constraint change on a table that already existed.
#
# Migrations therefore run HERE, from scripts/migrate.sh, and specifically
# BETWEEN the build and the recreate:
#
#     build images  ->  MIGRATE  ->  recreate backend and sync  ->  verify
#
# That order is chosen, not incidental:
#
#   * A failed migration must not leave new code running against an old schema.
#     Migrating first means a failure stops the deploy with the OLD containers
#     still serving (exit 3) -- the same failure shape as a failed build.
#   * The reverse order -- recreate, then migrate -- boots the new code against
#     a schema it does not have, which is a crash loop on a live site.
#   * env.py wraps the whole upgrade in one transaction and Postgres has
#     transactional DDL, so a failure rolls the schema back rather than leaving
#     it half applied.
#
# The cost of migrating first is real and worth naming: for the length of one
# rebuild, the OLD containers serve traffic against the NEW schema. Additive
# migrations (add a nullable column, add a table, add an index) are safe there.
# A destructive one is not, and the review checklist in every generated
# migration's docstring asks about exactly that.
#
# The alternative -- migrating from the app on startup -- was rejected: it
# couples schema changes to container restarts, races if there is ever more
# than one backend replica, and turns a bad migration into a crash loop instead
# of a deploy that stopped.
#
# Exit codes -- these are the contract, do not renumber casually:
#   0  deployed and verified
#   1  usage or preflight error, nothing touched
#   2  a gate refused, nothing touched
#   3  deploy step failed; git may have moved, but the running containers
#      were NOT replaced -- the service is still up on the old images.
#      A failed migration lands here, with the schema unchanged.
#   4  deploy succeeded but verification failed -- NEW CODE IS SERVING
#
set -euo pipefail

