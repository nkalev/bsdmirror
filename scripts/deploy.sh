banner() {
    # banner COLOR TITLE [line...]
    local color="$1" title="$2"; shift 2
    printf '\n%s%s\n' "$color" "========================================================================"
    printf '  %s\n' "$title"
    printf '%s\n' "========================================================================$C_OFF"
    local line
    for line in "$@"; do printf '  %s\n' "$line"; done
    printf '%s\n' "${color}========================================================================${C_OFF}"
}

